/**
 * End-of-study screen: debrief, a personal results dashboard, and the
 * completion / download actions. Rendered after jsPsych finishes.
 */
(function (root) {
  "use strict";

  const LABEL = { positive: "Positive", neutral: "Neutral", negative: "Negative" };
  const SAMPLE_WORD = { positive: "garden", neutral: "method", negative: "poison" };

  const pct = (x, digits = 0) => (x == null ? "—" : `${(x * 100).toFixed(digits)}%`);
  const ms = (x) => (x == null ? "—" : `${Math.round(x)} ms`);
  const num = (x, d = 2) => (x == null ? "—" : x.toFixed(d));
  const signed = (x) => (x == null ? "—" : `${x > 0 ? "+" : x < 0 ? "−" : "±"}${Math.abs(x * 100).toFixed(0)} pts`);

  function render(container, ctx) {
    const { summary: s, config: C, session } = ctx;
    const cats = ["positive", "neutral", "negative"];
    const L = C.luminance.reference;
    document.body.classList.add("results-mode");
    document.querySelector("#jspsych-progressbar-container")?.remove();

    container.innerHTML = `
      <main class="results">
        ${session.simulate ? `<div class="badge">Simulated participant — generated by jsPsych's simulation mode</div>` : ""}
        ${ctx.saveFailed ? saveFailedNotice(C) : ""}
        <header>
          <p class="eyebrow">Study complete</p>
          <h1>Thank you. Here's what was really going on.</h1>
          <p class="lede">We were interested in whether the <strong>emotional meaning of a word</strong> changes how
          bright the square after it looks. In the main part, <strong>every square was exactly the same grey as the
          reference</strong>. The repeated-word task made sure you were reading the words.</p>
        </header>

        <section class="reveal" aria-label="All main-part squares were identical">
          ${cats.map((c) => `
            <figure>
              <div class="reveal-word">${SAMPLE_WORD[c]}</div>
              <div class="swatch" style="--size:96px;background-color:rgb(${L},${L},${L})"></div>
              <figcaption>rgb(${L}, ${L}, ${L})</figcaption>
            </figure>`).join("")}
        </section>

        <section class="tiles">
          ${tile("Valence effect", signed(s.valence_effect), "“Brighter” after positive minus after negative words")}
          ${tile("Repeat detection", pct(s.cover.hit_rate), `${s.cover.hits}/${s.cover.targets} repeats · ${s.cover.false_alarms} false alarms · d′ ${num(s.cover.d_prime)}`)}
          ${tile("Rating agreement", pct(s.valence_ratings.agreement), "Your valence ratings vs. our word categories")}
          ${tile("Practice accuracy", pct(s.practice_accuracy), `Word duration ${num(s.word_duration.mean, 1)} ms (target ${C.timing.word_ms})`)}
        </section>

        <section class="card">
          <h2>How often you said “brighter”</h2>
          <p class="muted">Share of main-part responses judged brighter than the reference, by word category.
          With identical squares, no bias would put every bar near 50%.</p>
          ${brightnessChart(s, cats, chartWidth())}
        </section>

        <div class="grid-2">
          <section class="card">
            <h2>Response time</h2>
            <p class="muted">Mean time to judge the square, by preceding word.</p>
            ${rtChart(s, cats)}
          </section>
          <section class="card">
            <h2>Your ratings vs. our categories</h2>
            <p class="muted">Rows: our category. Columns: your rating.</p>
            ${confusion(s.valence_ratings.confusion, cats)}
          </section>
        </div>

        <details class="card table-view">
          <summary>Table view</summary>
          <table>
            <thead><tr><th>Category</th><th>Trials</th><th>Valid</th><th>“Brighter”</th><th>Mean RT</th><th>SD RT</th></tr></thead>
            <tbody>${cats.map((c) => { const b = s.by_category[c]; return `<tr><th>${LABEL[c]}</th><td>${b.n}</td><td>${b.n_valid}</td><td>${pct(b.p_brighter, 1)}</td><td>${ms(b.mean_rt)}</td><td>${ms(b.sd_rt)}</td></tr>`; }).join("")}</tbody>
          </table>
          <p class="muted">${s.excluded_trials} trial(s) excluded (no response, or RT outside ${C.design.min_valid_rt_ms}–${C.design.max_valid_rt_ms} ms).</p>
        </details>

        <p class="muted small">One person's data is noisy — the hypothesis is tested across all participants.
        Questions: ${C.study.contact}.</p>

        <div class="actions">
          ${ctx.completionUrl
            ? `<a class="btn primary" href="${ctx.completionUrl}">Complete study on Prolific</a>`
            : `<button class="btn primary" data-action="download">Download data (CSV)</button>
               <a class="btn" href="${location.pathname}">Take it again</a>
               <a class="btn" href="${location.pathname}?simulate=visual">Watch a simulated participant</a>`}
        </div>
      </main>
      <div class="tooltip" role="tooltip" hidden></div>`;

    container.querySelectorAll("[data-action=download]").forEach((b) => b.addEventListener("click", ctx.download));
    wireTooltips(container);
    container.scrollTop = 0;
    window.scrollTo(0, 0);
  }

  function saveFailedNotice(C) {
    return `<div class="notice" role="alert">
      <strong>We couldn't upload your data.</strong> Please download it and email it to ${C.study.contact}
      — you will still be paid.
      <button class="btn" data-action="download">Download data</button>
    </div>`;
  }

  function tile(label, value, detail) {
    return `<div class="tile"><div class="tile-label">${label}</div><div class="tile-value">${value}</div><div class="tile-detail">${detail}</div></div>`;
  }

  // Vertical bars on a 0–100 % scale with a dashed 50 % "no bias" line.
  // Drawn at (roughly) its on-screen width so text stays a readable size.
  function chartWidth() {
    return Math.round(Math.max(300, Math.min(840, window.innerWidth - 70)));
  }

  function brightnessChart(s, cats, W) {
    const H = W < 500 ? 240 : 300, m = { t: 24, r: 16, b: 36, l: 48 };
    const iw = W - m.l - m.r, ih = H - m.t - m.b;
    const y = (p) => m.t + ih * (1 - p);
    const band = iw / cats.length, bw = Math.min(88, band * 0.5);
    const grid = [0, 0.25, 0.5, 0.75, 1];
    return `<svg class="chart" viewBox="0 0 ${W} ${H}" role="img" aria-label="Percent brighter responses by word category">
      ${grid.map((g) => `<line class="grid" x1="${m.l}" x2="${W - m.r}" y1="${y(g)}" y2="${y(g)}"/>
        <text class="axis" x="${m.l - 8}" y="${y(g)}" dy="0.32em" text-anchor="end">${g * 100}%</text>`).join("")}
      ${cats.map((c, i) => {
        const b = s.by_category[c];
        const cx = m.l + band * i + band / 2;
        const p = b.p_brighter ?? 0;
        const h = Math.max(0, ih * p);
        return `<g class="mark" data-tip="<strong>${LABEL[c]}</strong><br>${pct(b.p_brighter, 1)} brighter<br>${b.n_valid} valid trials">
          <rect class="hit" x="${cx - band / 2}" y="${m.t}" width="${band}" height="${ih}"/>
          ${b.p_brighter == null ? "" : `<path class="bar cat-${c}" d="${roundedTop(cx - bw / 2, y(p), bw, h, 4)}"/>`}
          <text class="value" x="${cx}" y="${y(p) - 8}" text-anchor="middle">${pct(b.p_brighter)}</text>
          <text class="axis label" x="${cx}" y="${H - 12}" text-anchor="middle">${LABEL[c]}</text>
        </g>`;
      }).join("")}
      <line class="ref" x1="${m.l}" x2="${W - m.r}" y1="${y(0.5)}" y2="${y(0.5)}"/>
      <text class="axis ref-label" x="${W - m.r}" y="${y(0.5) - 6}" text-anchor="end">no bias</text>
    </svg>`;
  }

  // Horizontal bars for RT.
  function rtChart(s, cats) {
    const W = 360, rowH = 40, m = { l: 80, r: 64, t: 8 };
    const H = m.t * 2 + rowH * cats.length;
    const max = Math.max(1, ...cats.map((c) => s.by_category[c].mean_rt ?? 0));
    const x = (v) => ((W - m.l - m.r) * v) / max;
    return `<svg class="chart" viewBox="0 0 ${W} ${H}" role="img" aria-label="Mean response time by word category">
      <line class="grid" x1="${m.l}" x2="${m.l}" y1="${m.t}" y2="${H - m.t}"/>
      ${cats.map((c, i) => {
        const b = s.by_category[c];
        const yy = m.t + i * rowH + 10;
        const w = x(b.mean_rt ?? 0);
        return `<g class="mark" data-tip="<strong>${LABEL[c]}</strong><br>${ms(b.mean_rt)} mean · SD ${ms(b.sd_rt)}">
          <rect class="hit" x="0" y="${m.t + i * rowH}" width="${W}" height="${rowH}"/>
          <text class="axis label" x="${m.l - 10}" y="${yy + 10}" dy="0.32em" text-anchor="end">${LABEL[c]}</text>
          ${b.mean_rt == null ? "" : `<path class="bar cat-${c}" d="${roundedRight(m.l, yy, w, 20, 4)}"/>`}
          <text class="value" x="${m.l + w + 8}" y="${yy + 10}" dy="0.32em">${ms(b.mean_rt)}</text>
        </g>`;
      }).join("")}
    </svg>`;
  }

  // 3×3 heat table; single-hue sequential shading by row share.
  function confusion(matrix, cats) {
    return `<table class="confusion">
      <thead><tr><th></th>${cats.map((c) => `<th>${LABEL[c]}</th>`).join("")}</tr></thead>
      <tbody>${cats.map((r) => {
        const total = cats.reduce((a, c) => a + matrix[r][c], 0) || 1;
        return `<tr><th>${LABEL[r]}</th>${cats.map((c) => {
          const share = matrix[r][c] / total;
          return `<td class="${r === c ? "diag" : ""}" style="--share:${share.toFixed(3)}"
            data-tip="Our <strong>${LABEL[r].toLowerCase()}</strong> words you rated <strong>${LABEL[c].toLowerCase()}</strong>: ${matrix[r][c]} (${pct(share)})">${matrix[r][c]}</td>`;
        }).join("")}</tr>`;
      }).join("")}</tbody>
    </table>`;
  }

  function roundedTop(x, y, w, h, r) {
    if (h <= 0) return "";
    r = Math.min(r, h, w / 2);
    return `M${x},${y + h}V${y + r}Q${x},${y} ${x + r},${y}H${x + w - r}Q${x + w},${y} ${x + w},${y + r}V${y + h}Z`;
  }

  function roundedRight(x, y, w, h, r) {
    if (w <= 0) return "";
    r = Math.min(r, w, h / 2);
    return `M${x},${y}H${x + w - r}Q${x + w},${y} ${x + w},${y + r}V${y + h - r}Q${x + w},${y + h} ${x + w - r},${y + h}H${x}Z`;
  }

  function wireTooltips(container) {
    const tip = container.querySelector(".tooltip");
    container.querySelectorAll("[data-tip]").forEach((el) => {
      el.addEventListener("pointerenter", () => {
        tip.innerHTML = el.dataset.tip;
        tip.hidden = false;
      });
      el.addEventListener("pointermove", (e) => {
        const pad = 14;
        const x = Math.min(e.clientX + pad, window.innerWidth - tip.offsetWidth - 8);
        tip.style.transform = `translate(${x}px, ${e.clientY + pad}px)`;
      });
      el.addEventListener("pointerleave", () => (tip.hidden = true));
    });
  }

  root.BPE_RESULTS = { render };
})(self);
