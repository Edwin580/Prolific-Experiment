/**
 * End of study screen: debrief, the participant's own results, and the
 * completion / download actions. Rendered after jsPsych finishes.
 */
(function (root) {
  "use strict";

  const LABEL = { positive: "Positive", neutral: "Neutral", negative: "Negative" };
  const SAMPLE_WORD = { positive: "garden", neutral: "method", negative: "poison" };

  const pct = (x, digits = 0) => (x == null ? "n/a" : `${(x * 100).toFixed(digits)}%`);
  const ms = (x) => (x == null ? "n/a" : `${Math.round(x)} ms`);
  const num = (x, d = 2) => (x == null ? "n/a" : x.toFixed(d));
  const signed = (x) => (x == null ? "n/a" : `${x > 0 ? "+" : x < 0 ? "−" : "±"}${Math.abs(x * 100).toFixed(0)} points`);

  function render(container, ctx) {
    const { summary: s, config: C, session } = ctx;
    const cats = ["positive", "neutral", "negative"];
    const L = C.luminance.reference;
    document.body.classList.add("results-mode");
    document.querySelector("#jspsych-progressbar-container")?.remove();

    const c = s.cover;
    const eff = s.valence_effect;

    container.innerHTML = `
      <main class="results">
        ${session.simulate ? `<p class="note">Simulated participant, generated by jsPsych's simulation mode. These answers were not made by a person.</p>` : ""}
        <h1>Debrief: what was really going on</h1>
        <p>Thank you for taking part. The study asks whether the meaning of a word changes how bright the square after it
        looks. In the main part <b>every square was exactly the same grey as the reference</b>,
        <span class="code">rgb(${L}, ${L}, ${L})</span>. The task of spotting repeated words was there to make sure you read
        each word.</p>

        <figure>
          <div class="reveal" aria-label="All main part squares were identical">
            ${cats.map((cat) => `<div><span>${SAMPLE_WORD[cat]}</span>${swatch(L)}</div>`).join("")}
          </div>
          <figcaption><b>Figure 1.</b> A positive, a neutral and a negative word, each with the square that followed it. All three
            squares are the same.</figcaption>
        </figure>

        <h2>Your results</h2>
        <p>You said “brighter” ${pct(s.by_category.positive.p_brighter)} of the time after positive words and
        ${pct(s.by_category.negative.p_brighter)} after negative words${eff == null ? "" : `, a difference of ${signed(eff)}`}.
        You caught ${c.hits} of ${c.targets} repeated words with ${c.false_alarms} false
        ${c.false_alarms === 1 ? "alarm" : "alarms"} (<i>d</i>′ = ${num(c.d_prime)}), and your own ratings matched our word
        categories on ${pct(s.valence_ratings.agreement)} of words. Practice accuracy was ${pct(s.practice_accuracy)}.</p>

        <figure>
          ${brightnessChart(s, cats, chartWidth())}
          <figcaption><b>Figure 2.</b> Share of “brighter” answers in the main part by word category. The dashed line is 50%,
            where someone with no bias would land, since the squares never changed.</figcaption>
        </figure>

        <figure>
          <table>
            <thead><tr><th>Category</th><th>Trials</th><th>Valid</th><th>Brighter</th><th>Mean RT</th><th>SD RT</th></tr></thead>
            <tbody>${cats.map((cat) => { const b = s.by_category[cat]; return `<tr><th>${LABEL[cat]}</th><td>${b.n}</td><td>${b.n_valid}</td><td>${pct(b.p_brighter, 1)}</td><td>${ms(b.mean_rt)}</td><td>${ms(b.sd_rt)}</td></tr>`; }).join("")}</tbody>
          </table>
          <figcaption><b>Table 1.</b> Main part trials by category. ${s.excluded_trials} ${s.excluded_trials === 1 ? "trial was" : "trials were"} left out of the summaries
            for having no answer or a reaction time outside ${C.design.min_valid_rt_ms} to ${C.design.max_valid_rt_ms} ms.
            The word was on screen for ${num(s.word_duration.mean, 1)} ms on average (target ${C.timing.word_ms} ms).</figcaption>
        </figure>

        <figure>
          ${confusion(s.valence_ratings.confusion, cats)}
          <figcaption><b>Table 2.</b> Your ratings (columns) against our categories (rows). Matches are in bold.</figcaption>
        </figure>

        <p>One person's answers are noisy, so the hypothesis is tested across everyone who takes part. Questions:
        ${C.study.contact}.</p>

        <div class="actions">
          ${ctx.completionUrl
            ? `<a class="btn" href="${ctx.completionUrl}">Complete study on Prolific</a>
               <button class="btn" data-action="download">Download data again (CSV)</button>`
            : `<button class="btn" data-action="download">Download data (CSV)</button>
               <a class="btn" href="${location.pathname}">Take it again</a>
               <a class="btn" href="${location.pathname}?simulate=visual">Watch a simulated participant</a>
               <a class="btn" href="index.html">Back to the project page</a>`}
        </div>
      </main>`;

    container.querySelectorAll("[data-action=download]").forEach((b) => b.addEventListener("click", ctx.download));
    if (ctx.autoDownload) ctx.download();
    container.scrollTop = 0;
    window.scrollTo(0, 0);
  }

  function swatch(L) {
    return `<span class="swatch" style="background-color:rgb(${L},${L},${L})"></span>`;
  }

  function chartWidth() {
    return Math.round(Math.max(300, Math.min(648, window.innerWidth - 32)));
  }

  // Plain bar chart on a 0 to 100% scale with a dashed 50% line.
  function brightnessChart(s, cats, W) {
    const H = 240, m = { t: 22, r: 8, b: 30, l: 40 };
    const iw = W - m.l - m.r, ih = H - m.t - m.b;
    const y = (p) => m.t + ih * (1 - p);
    const band = iw / cats.length, bw = Math.min(70, band * 0.45);
    return `<svg class="chart" viewBox="0 0 ${W} ${H}" role="img" aria-label="Percent brighter answers by word category">
      ${[0, 0.5, 1].map((g) => `<text x="${m.l - 8}" y="${y(g)}" dy="0.32em" text-anchor="end">${g * 100}%</text>`).join("")}
      <line class="base" x1="${m.l}" x2="${W - m.r}" y1="${y(0)}" y2="${y(0)}"/>
      ${cats.map((c, i) => {
        const b = s.by_category[c];
        const cx = m.l + band * i + band / 2;
        const p = b.p_brighter ?? 0;
        return `${b.p_brighter == null ? "" : `<rect class="bar" x="${cx - bw / 2}" y="${y(p)}" width="${bw}" height="${ih * p}"/>`}
          <text class="value" x="${cx}" y="${y(p) - 7}" text-anchor="middle">${pct(b.p_brighter)}</text>
          <text x="${cx}" y="${H - 8}" text-anchor="middle">${LABEL[c]}</text>`;
      }).join("")}
      <line class="ref" x1="${m.l}" x2="${W - m.r}" y1="${y(0.5)}" y2="${y(0.5)}"/>
    </svg>`;
  }

  function confusion(matrix, cats) {
    return `<table class="confusion">
      <thead><tr><th></th>${cats.map((c) => `<th>${LABEL[c]}</th>`).join("")}</tr></thead>
      <tbody>${cats.map((r) => `<tr><th>${LABEL[r]}</th>${cats.map((c) =>
        `<td class="${r === c ? "diag" : ""}">${matrix[r][c]}</td>`).join("")}</tr>`).join("")}</tbody>
    </table>`;
  }

  root.BPE_RESULTS = { render };
})(self);
